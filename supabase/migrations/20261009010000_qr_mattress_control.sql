CREATE TABLE IF NOT EXISTS public.lmx_qr_scans (
  id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  stage             text NOT NULL CHECK (stage IN ('PACK','WAREHOUSE')),
  scanned_code      text NOT NULL,
  label_id          bigint REFERENCES public.lmx_qr_labels(id) ON DELETE SET NULL,
  result            text NOT NULL CHECK (result IN ('OK','ALREADY_SCANNED','NOT_FOUND','MODEL_MISMATCH','NOT_PACKED','VOIDED')),
  expected_sap_code text,
  label_sap_code    text,
  manual            boolean NOT NULL DEFAULT false,
  scanned_by        uuid DEFAULT auth.uid() REFERENCES auth.users(id) ON DELETE SET NULL,
  scanned_by_name   text,
  scanned_at        timestamptz NOT NULL DEFAULT now()
