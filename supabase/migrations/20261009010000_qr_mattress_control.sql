-- ============================================================
-- LAMITEX · CONTROL DE COLCHONES CON ETIQUETAS QR
-- Empaque → Bodega → Producción (oficina)
--
-- Migración ADITIVA: solo crea tablas, funciones y políticas nuevas
-- con prefijo lmx_qr_. No modifica product_models, product_skus,
-- user_profiles ni ninguna otra tabla existente (solo las referencia).
-- ============================================================
BEGIN;

-- ------------------------------------------------------------
-- 1. ACCESO A LOS MÓDULOS QR
--    ADMIN     → los 4 módulos (los ADMIN del ERP también lo son)
--    PACKER    → solo Empaque
--    WAREHOUSE → solo Bodega
--    OFFICE    → solo Producción / reportes
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.lmx_qr_user_access (
  user_id      uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  module_role  text NOT NULL CHECK (module_role IN ('ADMIN','PACKER','WAREHOUSE','OFFICE')),
  display_name text,
  active       boolean NOT NULL DEFAULT true,
  created_at   timestamptz NOT NULL DEFAULT now(),
  updated_at   timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.lmx_qr_user_access ENABLE ROW LEVEL SECURITY;

DROP TRIGGER IF EXISTS trg_lmx_qr_user_access_updated_at ON public.lmx_qr_user_access;
CREATE TRIGGER trg_lmx_qr_user_access_updated_at BEFORE UPDATE ON public.lmx_qr_user_access
FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

-- Rol efectivo del usuario actual en los módulos QR (NULL = sin acceso).
CREATE OR REPLACE FUNCTION public.lmx_qr_role()
RETURNS text LANGUAGE sql STABLE SECURITY DEFINER SET search_path = '' AS $$
  SELECT CASE
    WHEN public.has_any_role(ARRAY['ADMIN']) THEN 'ADMIN'
    ELSE (SELECT a.module_role FROM public.lmx_qr_user_access a WHERE a.user_id = auth.uid() AND a.active)
  END;
$$;

CREATE OR REPLACE FUNCTION public.lmx_qr_can(allowed text[])
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = '' AS $$
  SELECT COALESCE(public.lmx_qr_role() = 'ADMIN' OR public.lmx_qr_role() = ANY (allowed), false);
$$;

REVOKE ALL ON FUNCTION public.lmx_qr_role() FROM PUBLIC;
REVOKE ALL ON FUNCTION public.lmx_qr_can(text[]) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.lmx_qr_role() TO authenticated;
GRANT EXECUTE ON FUNCTION public.lmx_qr_can(text[]) TO authenticated;

DROP POLICY IF EXISTS lmx_qr_access_select ON public.lmx_qr_user_access;
CREATE POLICY lmx_qr_access_select ON public.lmx_qr_user_access FOR SELECT TO authenticated
  USING (user_id = auth.uid() OR public.lmx_qr_can(ARRAY['ADMIN']));
DROP POLICY IF EXISTS lmx_qr_access_admin_write ON public.lmx_qr_user_access;
CREATE POLICY lmx_qr_access_admin_write ON public.lmx_qr_user_access FOR ALL TO authenticated
  USING (public.lmx_qr_can(ARRAY['ADMIN'])) WITH CHECK (public.lmx_qr_can(ARRAY['ADMIN']));

-- ------------------------------------------------------------
-- 2. LOTES DE IMPRESIÓN, LÍNEAS Y ETIQUETAS
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.lmx_qr_batches (
  id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  programmer        text NOT NULL CHECK (length(trim(programmer)) > 0),
  observation       text,
  sticker_width_mm  numeric(6,1) NOT NULL DEFAULT 100 CHECK (sticker_width_mm BETWEEN 20 AND 300),
  sticker_height_mm numeric(6,1) NOT NULL DEFAULT 50  CHECK (sticker_height_mm BETWEEN 15 AND 300),
  total_labels      integer NOT NULL DEFAULT 0,
  created_by        uuid DEFAULT auth.uid() REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at        timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.lmx_qr_batch_lines (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  batch_id       bigint NOT NULL REFERENCES public.lmx_qr_batches(id) ON DELETE CASCADE,
  product_sku_id bigint REFERENCES public.product_skus(id) ON DELETE SET NULL,
  sap_code       text NOT NULL,
  model_name     text NOT NULL,
  measure        text,
  quantity       integer NOT NULL CHECK (quantity BETWEEN 1 AND 2000),
  observation    text
);
CREATE INDEX IF NOT EXISTS lmx_qr_batch_lines_batch_idx ON public.lmx_qr_batch_lines(batch_id);

CREATE TABLE IF NOT EXISTS public.lmx_qr_labels (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code           text NOT NULL UNIQUE,
  batch_id       bigint NOT NULL REFERENCES public.lmx_qr_batches(id) ON DELETE RESTRICT,
  line_id        bigint NOT NULL REFERENCES public.lmx_qr_batch_lines(id) ON DELETE RESTRICT,
  seq            integer NOT NULL,
  product_sku_id bigint REFERENCES public.product_skus(id) ON DELETE SET NULL,
  sap_code       text NOT NULL,
  model_name     text NOT NULL,
  measure        text,
  created_at     timestamptz NOT NULL DEFAULT now(),
  -- Etapa 1: empaque (una sola vez)
  packed_at      timestamptz,
  packed_by      uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  packed_manual  boolean,
  -- Etapa 2: bodega (una sola vez)
  received_at    timestamptz,
  received_by    uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  received_manual boolean,
  -- Anulación (etiqueta dañada / no usada)
  voided_at      timestamptz,
  voided_by      uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  void_reason    text,
  CONSTRAINT lmx_qr_labels_stage_order CHECK (received_at IS NULL OR packed_at IS NOT NULL)
);
CREATE INDEX IF NOT EXISTS lmx_qr_labels_batch_idx    ON public.lmx_qr_labels(batch_id);
CREATE INDEX IF NOT EXISTS lmx_qr_labels_packed_idx   ON public.lmx_qr_labels(packed_at);
CREATE INDEX IF NOT EXISTS lmx_qr_labels_received_idx ON public.lmx_qr_labels(received_at);
CREATE INDEX IF NOT EXISTS lmx_qr_labels_sap_idx      ON public.lmx_qr_labels(sap_code);

-- Bloqueo definitivo: una vez registrada una etapa, ya no se puede cambiar ni borrar.
CREATE OR REPLACE FUNCTION public.lmx_qr_labels_lock()
RETURNS trigger LANGUAGE plpgsql SET search_path = '' AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION 'Las etiquetas QR no se pueden borrar; anúlalas.';
  END IF;
  IF OLD.packed_at IS NOT NULL AND NEW.packed_at IS DISTINCT FROM OLD.packed_at
     OR OLD.packed_by IS NOT NULL AND NEW.packed_by IS DISTINCT FROM OLD.packed_by THEN
    RAISE EXCEPTION 'La etiqueta % ya fue escaneada en empaque.', OLD.code;
  END IF;
  IF OLD.received_at IS NOT NULL AND NEW.received_at IS DISTINCT FROM OLD.received_at
     OR OLD.received_by IS NOT NULL AND NEW.received_by IS DISTINCT FROM OLD.received_by THEN
    RAISE EXCEPTION 'La etiqueta % ya fue escaneada en bodega.', OLD.code;
  END IF;
  IF NEW.code <> OLD.code OR NEW.sap_code <> OLD.sap_code OR NEW.batch_id <> OLD.batch_id THEN
    RAISE EXCEPTION 'Los datos de origen de la etiqueta no se pueden cambiar.';
  END IF;
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS trg_lmx_qr_labels_lock ON public.lmx_qr_labels;
CREATE TRIGGER trg_lmx_qr_labels_lock BEFORE UPDATE OR DELETE ON public.lmx_qr_labels
FOR EACH ROW EXECUTE FUNCTION public.lmx_qr_labels_lock();

